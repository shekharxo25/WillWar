#!/usr/bin/env node
// Generates the PWA icon set and iOS launch images into public/icons/.
// The mark: one chalk tally group (four strokes and a strike) in tape white on the gym floor. No text.
// Uses sharp (installed with Next.js). Run: npm run icons
import { mkdirSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const OUT = new URL("../public/icons/", import.meta.url);
mkdirSync(OUT, { recursive: true });
mkdirSync(new URL("launch/", OUT), { recursive: true });

// Literal colors (icons are rendered outside the page): --text, --bg, --housing.
const TAPE = "#ECEAE4";
const FLOOR = "#262422";
const HOUSING = "#0E0E0E";

/** The tally group drawn in a 100x100 box, hand-drawn with fixed (deterministic) jitter. */
function mark(color, stroke = 7) {
  const s = `stroke="${color}" stroke-width="${stroke}" stroke-linecap="round" fill="none"`;
  return `
    <path ${s} d="M24 18 Q23 50 25 82"/>
    <path ${s} d="M40 17 Q41.5 50 39.5 83"/>
    <path ${s} d="M56 18.5 Q55 50 56.5 81.5"/>
    <path ${s} d="M72 17 Q73 50 71 82.5"/>
    <path ${s} d="M12 70 Q50 52 88 30"/>`;
}

/** SVG of `size` with the mark scaled to `fraction` of the canvas, centered. */
function svg({ size, fraction, bg, color = TAPE, w = 0, h = 0 }) {
  const W = w || size;
  const H = h || size;
  const m = Math.min(W, H) * fraction;
  const x = (W - m) / 2;
  const y = (H - m) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
    ${bg ? `<rect width="${W}" height="${H}" fill="${bg}"/>` : ""}
    <g transform="translate(${x} ${y}) scale(${m / 100})">${mark(color)}</g>
  </svg>`;
}

async function png(name, opts) {
  await sharp(Buffer.from(svg(opts))).png().toFile(new URL(name, OUT).pathname);
}

await png("icon-192.png", { size: 192, fraction: 0.62, bg: FLOOR });
await png("icon-512.png", { size: 512, fraction: 0.62, bg: FLOOR });
await png("apple-touch-icon.png", { size: 180, fraction: 0.62, bg: FLOOR }); // opaque: iOS ignores transparency
await png("maskable-512.png", { size: 512, fraction: 0.5, bg: FLOOR }); // mark well inside the central 80%
await png("monochrome-512.png", { size: 512, fraction: 0.62, bg: null, color: "#FFFFFF" });
await png("favicon-32.png", { size: 32, fraction: 0.8, bg: FLOOR });
writeFileSync(new URL("favicon.svg", OUT), svg({ size: 64, fraction: 0.8, bg: FLOOR }).replace(/\n\s*/g, ""));

// iOS launch images (portrait, device pixels) with the mark centered on the housing black.
const LAUNCH = [
  { w: 1320, h: 2868, dw: 440, dh: 956, r: 3 }, // 16 Pro Max
  { w: 1206, h: 2622, dw: 402, dh: 874, r: 3 }, // 16 Pro
  { w: 1290, h: 2796, dw: 430, dh: 932, r: 3 }, // 15 Plus / Pro Max, 16 Plus
  { w: 1179, h: 2556, dw: 393, dh: 852, r: 3 }, // 15 / 15 Pro / 16
  { w: 1284, h: 2778, dw: 428, dh: 926, r: 3 }, // 12-14 Pro Max / 14 Plus
  { w: 1170, h: 2532, dw: 390, dh: 844, r: 3 }, // 12-14
  { w: 1125, h: 2436, dw: 375, dh: 812, r: 3 }, // X / XS / 11 Pro / mini
  { w: 828, h: 1792, dw: 414, dh: 896, r: 2 }, // XR / 11
  { w: 750, h: 1334, dw: 375, dh: 667, r: 2 }, // SE 2/3, 8
];
const links = [];
for (const l of LAUNCH) {
  const name = `launch/launch-${l.w}x${l.h}.png`;
  await png(name, { size: 0, w: l.w, h: l.h, fraction: 0.22, bg: HOUSING });
  links.push({
    url: `/icons/${name}`,
    media: `(device-width: ${l.dw}px) and (device-height: ${l.dh}px) and (-webkit-device-pixel-ratio: ${l.r}) and (orientation: portrait)`,
  });
}
writeFileSync(
  new URL("../src/components/shell/launch-images.ts", import.meta.url),
  `// Generated by scripts/make-icons.mjs. Use in metadata.appleWebApp.startupImage.\nexport const LAUNCH_IMAGES = ${JSON.stringify(links, null, 2)};\n`,
);
console.log(`icons written to public/icons (${LAUNCH.length} launch images)`);
